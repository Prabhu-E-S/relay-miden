import 'fake-indexeddb/auto';
import { describe, it, expect } from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createServerInstance } from '../../server/src/app';
import { LanConnectionManager } from './services/lan/connection';
import { taskRepository } from './db/task-repository';
import { getOutboxEntries } from './services/lan/outbox';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const webDir = path.resolve(__dirname, '..');
const distDir = path.join(webDir, 'dist');
const publicDir = path.join(webDir, 'public');

describe('Phase 8 — Progressive Web App, Offline Launch & Secure LAN Access', () => {
  describe('Web App Manifest Invariants', () => {
    const manifestPath = path.join(distDir, 'manifest.webmanifest');

    it('generates a valid web manifest on production build', () => {
      expect(fs.existsSync(manifestPath), 'manifest.webmanifest must exist in dist/').toBe(true);
    });

    it('manifest defines exact metadata, standalone mode, and brand colors', () => {
      const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));

      expect(manifest.name).toBe('Relay Miden');
      expect(manifest.short_name).toBe('Relay Miden');
      expect(manifest.description).toContain(
        'Offline-first multilingual volunteer and task coordination',
      );
      expect(manifest.display).toBe('standalone');
      expect(manifest.start_url).toBe('/');
      expect(manifest.scope).toBe('/');
      expect(manifest.theme_color).toBe('#004225'); // Forest green brand token
      expect(manifest.background_color).toBe('#F5F5DC'); // Beige brand token
    });

    it('manifest includes standard, maskable, and high-resolution icons', () => {
      const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
      const icons = manifest.icons as Array<{
        src: string;
        sizes: string;
        type: string;
        purpose?: string;
      }>;

      expect(icons).toBeDefined();
      expect(icons.length).toBeGreaterThanOrEqual(3);

      const icon192 = icons.find((i) => i.sizes === '192x192' && i.purpose !== 'maskable');
      const icon512 = icons.find((i) => i.sizes === '512x512' && i.purpose !== 'maskable');
      const maskable512 = icons.find((i) => i.sizes === '512x512' && i.purpose === 'maskable');

      expect(icon192).toBeDefined();
      expect(icon512).toBeDefined();
      expect(maskable512).toBeDefined();

      // Ensure physical files exist in public directory
      expect(fs.existsSync(path.join(publicDir, 'pwa-192x192.png'))).toBe(true);
      expect(fs.existsSync(path.join(publicDir, 'pwa-512x512.png'))).toBe(true);
      expect(fs.existsSync(path.join(publicDir, 'pwa-maskable-512x512.png'))).toBe(true);
      expect(fs.existsSync(path.join(publicDir, 'apple-touch-icon.png'))).toBe(true);
      expect(fs.existsSync(path.join(publicDir, 'favicon.svg'))).toBe(true);
      expect(fs.existsSync(path.join(publicDir, 'favicon.ico'))).toBe(true);
    });
  });

  describe('Service Worker & App Shell Caching Invariants', () => {
    const swPath = path.join(distDir, 'sw.js');

    it('generates a service worker script on build', () => {
      expect(fs.existsSync(swPath), 'sw.js must exist in dist/').toBe(true);
    });

    it('precaches core app shell assets (HTML, CSS, JS, fonts, icons)', () => {
      const swContent = fs.readFileSync(swPath, 'utf8');

      // Check precached entries generated by Workbox
      expect(swContent).toContain('index.html');
      expect(swContent).toMatch(/index-.*\.js/);
      expect(swContent).toMatch(/index-.*\.css/);
      expect(swContent).toMatch(/dm-sans-.*\.woff2?/);
      expect(swContent).toContain('pwa-192x192.png');
      expect(swContent).toContain('pwa-512x512.png');
    });

    it('excludes LAN sync, Socket.IO, and API endpoints from precache & navigation fallback', () => {
      const swContent = fs.readFileSync(swPath, 'utf8');

      // Ensure workbox navigateFallback denylist contains api, socket.io, and health patterns
      expect(swContent.includes('socket\\.io')).toBe(true);
      expect(swContent.includes('api')).toBe(true);
      expect(swContent.includes('health')).toBe(true);
    });
  });

  describe('Secure Context & HTTPS LAN Configuration', () => {
    it('LAN connection manager validates and supports both http and https URLs', () => {
      const manager = new LanConnectionManager();

      expect(() => manager.validateUrl('http://192.168.1.50:3001')).not.toThrow();
      expect(() => manager.validateUrl('https://10.10.19.44:3001')).not.toThrow();
      expect(() => manager.validateUrl('https://relay.local:3001')).not.toThrow();
      expect(() => manager.validateUrl('ftp://10.10.19.44:3001')).toThrow(
        /LAN URL must use http: or https:/,
      );
      expect(() => manager.validateUrl('not-a-valid-url')).toThrow(/Invalid LAN server URL/);
    });

    it('Express server creates HTTPS server when httpsKey and httpsCert are configured', async () => {
      const certDir = path.resolve(webDir, '../../certs');
      const keyPath = path.join(certDir, 'dev-key.pem');
      const certPath = path.join(certDir, 'dev-cert.pem');

      if (fs.existsSync(keyPath) && fs.existsSync(certPath)) {
        const testDbPath = path.join(
          webDir,
          `../../apps/server/data/test-https-${Date.now()}.sqlite`,
        );
        const serverInstance = createServerInstance({
          port: 0,
          dbPath: testDbPath,
          httpsKey: keyPath,
          httpsCert: certPath,
        });

        expect(serverInstance.config.httpsKey).toBe(keyPath);
        expect(serverInstance.config.httpsCert).toBe(certPath);

        // Verify the underlying server is an HTTPS server
        expect(serverInstance.httpServer.constructor.name).toBe('Server');

        await serverInstance.close();
        try {
          if (fs.existsSync(testDbPath)) fs.unlinkSync(testDbPath);
        } catch {
          // ignore
        }
      }
    });
  });

  describe('Data Safety & IndexedDB Preservation', () => {
    it('local IndexedDB tasks and durable outbox operations remain intact during app shell updates', async () => {
      // 1. Create a task in IndexedDB
      const task = await taskRepository.createTask({
        title: 'Offline PWA preservation verification',
        quantity: 50,
        unit: 'Kits',
        location: 'Zone 4 Shelter',
        priority: 'high',
        description: 'Verifying task survives PWA cache updates without data loss.',
      });

      expect(task).toBeDefined();
      expect(task.title).toBe('Offline PWA preservation verification');

      // 2. Verify durable outbox queue contains the corresponding PENDING operation
      const pending = await getOutboxEntries('PENDING');
      const taskOutbox = pending.find((e) => e.taskId === task.id);
      expect(taskOutbox).toBeDefined();
      expect(taskOutbox?.status).toBe('PENDING');

      // 3. Retrieve task from repository to ensure persistent durability
      const retrieved = await taskRepository.getTaskById(task.id);
      expect(retrieved).toBeDefined();
      expect(retrieved?.id).toBe(task.id);

      // Clean up test task
      await taskRepository.deleteTask(task.id);
    });
  });
});
